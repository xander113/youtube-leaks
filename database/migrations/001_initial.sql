CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
  email TEXT UNIQUE,
  name TEXT NOT NULL,
  password_hash TEXT,
  role TEXT NOT NULL DEFAULT 'watcher',
  banned_at BIGINT,
  stripe_customer_id TEXT UNIQUE,
  plan TEXT CHECK (plan IN ('basic', 'premium')),
  paid_until BIGINT,
  billing_revision BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  CHECK ((id = 1 AND role = 'admin' AND banned_at IS NULL) OR (id > 1 AND role IN ('admin','watcher')))
);

CREATE TABLE settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  paid INTEGER NOT NULL DEFAULT 0 CHECK (paid IN (0,1))
);

CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE INDEX sessions_expiry ON sessions(expires_at);

CREATE TABLE series (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  category TEXT NOT NULL,
  random_order INTEGER NOT NULL DEFAULT 0 CHECK (random_order IN (0,1)),
  created_at BIGINT NOT NULL
);
CREATE INDEX series_newest ON series(created_at DESC, id);

CREATE TABLE feeds (
  id TEXT PRIMARY KEY,
  url TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL,
  series_id TEXT REFERENCES series(id),
  guest INTEGER NOT NULL DEFAULT 0 CHECK (guest IN (0,1)),
  enabled INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0,1)),
  due_at BIGINT NOT NULL,
  started_at BIGINT,
  last_run BIGINT,
  last_error TEXT
);
CREATE INDEX feeds_due ON feeds(enabled, due_at);

CREATE TABLE clips (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  category TEXT NOT NULL,
  guest INTEGER NOT NULL DEFAULT 0 CHECK (guest IN (0,1)),
  series_id TEXT REFERENCES series(id),
  source_id TEXT UNIQUE,
  status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','processing','ready','failed')),
  job_error TEXT,
  started_at BIGINT,
  created_at BIGINT NOT NULL,
  published_at BIGINT NOT NULL,
  duration INTEGER,
  demo INTEGER NOT NULL DEFAULT 0 CHECK (demo IN (0,1))
);
CREATE INDEX clips_recent ON clips(status, published_at DESC, id);
CREATE INDEX clips_public ON clips(status, guest, published_at DESC, id);
CREATE INDEX clips_series ON clips(series_id, status, published_at, id);
CREATE INDEX clips_queue ON clips(status, created_at);

CREATE TABLE comments (
  id TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  target_type TEXT NOT NULL CHECK (target_type IN ('clip','series')),
  target_id TEXT NOT NULL,
  parent_id TEXT REFERENCES comments(id) ON DELETE CASCADE,
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX comments_target ON comments(target_type, target_id, parent_id, created_at DESC, id);
CREATE INDEX comments_parent ON comments(parent_id);

CREATE TABLE playlists (
  id TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX playlists_user ON playlists(user_id, created_at);

CREATE TABLE playlist_items (
  playlist_id TEXT NOT NULL REFERENCES playlists(id) ON DELETE CASCADE,
  target_type TEXT NOT NULL CHECK (target_type IN ('clip','series')),
  target_id TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (playlist_id, target_type, target_id)
);

CREATE TABLE support_requests (
  id TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  body TEXT NOT NULL,
  priority INTEGER NOT NULL CHECK (priority IN (0,1)),
  created_at BIGINT NOT NULL,
  answer TEXT,
  answered_at BIGINT
);
CREATE INDEX support_user ON support_requests(user_id, created_at DESC);
CREATE INDEX support_queue ON support_requests(answered_at, priority DESC, created_at);
